// ──────────────────────────────────────────────
// Free-float table generator — writes backend/lib/freefloat.js
// ──────────────────────────────────────────────
// IHSG is weighted by FREE-FLOAT market cap, so attributing a day's index move
// to individual stocks (scrapers/movers.js) needs each company's free-float
// ratio. Yahoo's float figure sits behind quoteSummary (401) and IDX's own
// free-float report is behind Cloudflare, so this reads the "Float" and
// "Shares Outstanding" figures stockanalysis.com prints on each IDX
// statistics page — fetchable server-side, no auth.
//
// Their float definition (shares not held by insiders or large holders) is
// close to, not identical with, IDX's (scripless shares held by investors
// under 5%, excluding directors and treasury). Close enough to matter: over
// 2025-09 → 2026-10, weighting by this table rebuilt the IHSG's daily point
// move with a 7-point mean miss, against 14 points for full market cap.
//
// Floats move slowly; re-run alongside the quarterly HSC review (lib/ihsg-rules.js):
//   node backend/scrape-free-float.js
// ~5 minutes for the full listing. Commit the regenerated lib/freefloat.js.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { IDX_TICKERS } from './lib/tickers.js';

const OUT = fileURLToPath(new URL('./lib/freefloat.js', import.meta.url));
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const BATCH_SIZE = 4;
const BATCH_DELAY = 1200;

// The page embeds its statistics as `{id:"float",...,hover:"48,610,141,397"}`;
// `hover` carries the unabbreviated figure.
function parseStat(html, id) {
  const m = html.match(new RegExp(`\\{id:"${id}",title:"[^"]*",value:"[^"]*",hover:"([^"]*)"`));
  if (!m) return null;
  const v = parseFloat(m[1].replace(/,/g, ''));
  return Number.isFinite(v) && v > 0 ? v : null;
}

async function floatRatio(code) {
  const res = await fetch(`https://stockanalysis.com/quote/idx/${code}/statistics/`, {
    headers: { 'User-Agent': UA },
    signal: AbortSignal.timeout(20000),
  });
  if (!res.ok) return null;
  const html = await res.text();
  const float = parseStat(html, 'float');
  const out = parseStat(html, 'sharesout');
  if (!float || !out) return null;
  return Math.min(1, float / out);
}

const ratios = {};
for (let i = 0; i < IDX_TICKERS.length; i += BATCH_SIZE) {
  const batch = IDX_TICKERS.slice(i, i + BATCH_SIZE);
  const results = await Promise.all(batch.map(code => floatRatio(code).catch(() => null)));
  batch.forEach((code, j) => { if (results[j] != null) ratios[code] = parseFloat(results[j].toFixed(3)); });
  if (i % 100 === 0) console.log(`${i}/${IDX_TICKERS.length} — ${Object.keys(ratios).length} with a float`);
  await new Promise(r => setTimeout(r, BATCH_DELAY));
}

const asOf = new Date().toISOString().slice(0, 10);
const entries = Object.keys(ratios).sort().map(code => `${code}:${ratios[code]}`);
const lines = [];
for (let i = 0; i < entries.length; i += 8) lines.push('  ' + entries.slice(i, i + 8).join(', ') + ',');

writeFileSync(OUT, `// GENERATED by backend/scrape-free-float.js — do not edit by hand; re-run it.
// Free-float ratio (float shares / shares outstanding) per IDX code, from
// stockanalysis.com, as of ${asOf}. ${entries.length} of ${IDX_TICKERS.length} listed codes carry a figure;
// the rest fall back to the median (see scrapers/movers.js).

export const FREE_FLOAT_AS_OF = '${asOf}';

export const FREE_FLOAT = {
${lines.join('\n')}
};
`);
console.log(`Wrote ${entries.length} floats to ${OUT}`);
